std::span<const RegValue> InitSettings() { return kInitSettings; }

std::span<const RegValue> BitDepth(PixelFormat format) {
  switch (format) {
    case PixelFormat::RAW_10:
      return kBitDepth10;
    case PixelFormat::RAW_12:
      return kBitDepth12;
    default:
      throw std::invalid_argument("IMX676 outputs RAW10 or RAW12 only");
  }
}

std::span<const RegValue> ReadoutTable(Readout readout) {
  switch (readout) {
    case Readout::kAllPixel:
      return kAllPixel;
    case Readout::kCrop:
      return kCrop;
    case Readout::kBinning2x2:
      return kBinning2x2;
  }
  throw std::invalid_argument("unknown IMX676 readout");
}

std::span<const RegValue> TestPatternEnable() { return kTpgEnable; }
std::span<const RegValue> TestPatternDisable() { return kTpgDisable; }
std::span<const RegValue> StartSequence() { return kStart; }
std::span<const RegValue> StopSequence() { return kStop; }

